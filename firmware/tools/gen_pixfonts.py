"""Bake the themes' built-in fonts into firmware/ui/pixfont.h (ASCII 32..126 only: they
draw labels, headings and dot-matrix text, never song titles -- those stay in the card's
fonts with their CJK fallback). Built into the firmware so no card refresh is needed.

  PF_POSTER11  Archivo Black 11 px, anti-aliased (8-bit alpha): the Sakurai menu's small labels
  PF_PIXEL11   Pixelify Sans 11 px, 1-bit: pixel-exact at 11 (its design pixel is ~91/1000 em);
               the pixel themes draw it on their 2x2 grid (22 px)
  PF_SILK8     Silkscreen 8 px, 1-bit (5-dot capitals): the receiver's dot-matrix, small labels
  PF_SILK16    Silkscreen 16 px, 1-bit: the dot-matrix's big station names

  .venv/Scripts/python firmware/tools/gen_pixfonts.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FD = ROOT / "firmware" / "assets" / "fonts"
OUT = ROOT / "firmware" / "ui" / "pixfont.h"

FONTS = [  # name, file, px, variation, 1-bit?
    ("POSTER11", "ArchivoBlack-Regular.ttf", 11, None, False),
    ("PIXEL11", "PixelifySans.ttf", 11, "Regular", True),
    ("SILK8", "Silkscreen.ttf", 8, None, True),
    ("SILK16", "Silkscreen.ttf", 16, None, True),
]
FIRST, LAST = 32, 126


def bake(name, file, px, var, mono):
    f = ImageFont.truetype(str(FD / file), px)
    if var:
        f.set_variation_by_name(var)
    asc, desc = f.getmetrics()
    h = asc + desc
    offs, widths, data = [], [], bytearray()
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        w = max(1, int(round(f.getlength(ch))))
        im = Image.new("L", (w + 2, h), 0)
        d = ImageDraw.Draw(im)
        if mono:
            d.fontmode = "1"
        d.text((0, 0), ch, font=f, fill=255)
        im = im.crop((0, 0, w, h))
        offs.append(len(data))
        widths.append(w)
        px_ = im.load()
        if mono:
            for y in range(h):
                for xb in range(0, w, 8):
                    b = 0
                    for k in range(8):
                        if xb + k < w and px_[xb + k, y] >= 128:
                            b |= 0x80 >> k
                    data.append(b)
        else:
            for y in range(h):
                for x in range(w):
                    data.append(px_[x, y])
    lines = [f"/* {name}: {file} {px}px{' (1-bit)' if mono else ''}, line {h}, baseline {asc} */"]
    lines.append(f"static const uint8_t pf_{name.lower()}_data[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const uint16_t pf_{name.lower()}_off[{len(offs)}] = {{ " + ", ".join(map(str, offs)) + " };")
    lines.append(f"static const uint8_t pf_{name.lower()}_w[{len(widths)}] = {{ " + ", ".join(map(str, widths)) + " };")
    lines.append(f"static const pixfont PF_{name} = {{ {h}, {asc}, {1 if mono else 0}, "
                 f"pf_{name.lower()}_off, pf_{name.lower()}_w, pf_{name.lower()}_data }};")
    return "\n".join(lines), len(data)


def main():
    parts = ["/* generated by firmware/tools/gen_pixfonts.py -- do not edit */",
             "#ifndef CODA_PIXFONT_H", "#define CODA_PIXFONT_H", "#include <stdint.h>", "",
             "typedef struct {", "    uint8_t h, base, mono;            /* line height, baseline, 1-bit? */",
             "    const uint16_t *off;               /* per glyph (ASCII 32..126): offset into data */",
             "    const uint8_t *w;                  /* per glyph: width = advance */",
             "    const uint8_t *data;               /* 1-bit rows (MSB first, padded to a byte) or 8-bit alpha */",
             "} pixfont;", ""]
    total = 0
    for spec in FONTS:
        s, n = bake(*spec)
        parts.append(s)
        parts.append("")
        total += n
    parts.append("#endif")
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({total} bytes of glyphs)")


if __name__ == "__main__":
    main()
