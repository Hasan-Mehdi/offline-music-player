r"""Bake the boot animation's "Coda" wordmark into firmware/ui/wordmark.h.

The first boot frame is drawn before the card is mounted, so it can't use the glyph atlases
on the card: the wordmark ships inside the firmware as an 8-bit alpha bitmap (Archivo Black,
rendered 4x and box-downsampled like every other glyph Coda draws).

  .venv\Scripts\python firmware\tools\gen_wordmark.py
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "firmware" / "assets" / "fonts" / "ArchivoBlack-Regular.ttf"
OUT = ROOT / "firmware" / "ui" / "wordmark.h"
TEXT, PX, SS, TRACK = "Coda", 44, 4, -0.04   # tracking in em, like the web masthead


def main():
    f = ImageFont.truetype(str(FONT), PX * SS)
    asc, desc = f.getmetrics()
    w = int(sum(f.getlength(c) for c in TEXT) + 40 * SS)
    img = Image.new("L", (w, asc + desc + 8 * SS), 0)
    d = ImageDraw.Draw(img)
    x = 4 * SS
    for c in TEXT:
        d.text((x, 4 * SS), c, font=f, fill=255)
        x += f.getlength(c) + TRACK * PX * SS
    a = np.asarray(img, dtype=np.float32)
    h4, w4 = a.shape[0] // SS * SS, a.shape[1] // SS * SS
    a = a[:h4, :w4].reshape(h4 // SS, SS, w4 // SS, SS).mean(axis=(1, 3))
    ys, xs = np.nonzero(a > 2)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    a = np.clip(a[y0:y1, x0:x1] + 0.5, 0, 255).astype(np.uint8)
    baseline = (4 * SS + asc) // SS - y0                     # rows from the top to the baseline
    rows = [", ".join(str(v) for v in r) for r in a]
    OUT.write_text(
        "/* generated by firmware/tools/gen_wordmark.py -- \"Coda\" in Archivo Black, "
        f"{PX}px, 8-bit alpha */\n"
        "#ifndef CODA_WORDMARK_H\n#define CODA_WORDMARK_H\n#include <stdint.h>\n"
        f"#define WORDMARK_W {a.shape[1]}\n#define WORDMARK_H {a.shape[0]}\n"
        f"#define WORDMARK_BASELINE {baseline}\n"
        "static const uint8_t wordmark_a8[WORDMARK_W * WORDMARK_H] = {\n"
        + ",\n".join("    " + r for r in rows) + "\n};\n#endif\n", newline="\n")
    print(f"{OUT}: {a.shape[1]}x{a.shape[0]}, baseline {baseline}")


if __name__ == "__main__":
    main()
