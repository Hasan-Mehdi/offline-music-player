r"""Bake the boot animation's type into firmware/ui/wordmark.h.

The first boot frame is drawn before the card is mounted, so it can't use the glyph atlases
on the card: the wordmark ("Coda", Archivo Black) and the line under it ("music, offline",
Inconsolata) ship inside the firmware as 8-bit alpha bitmaps, rendered 4x and
box-downsampled like every other glyph Coda draws. Sizes as in docs/h2/boot/v2 (B).

  .venv\Scripts\python firmware\tools\gen_wordmark.py
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "firmware" / "assets" / "fonts"
OUT = ROOT / "firmware" / "ui" / "wordmark.h"
SS = 4
PARTS = (   # name, text, font, px, tracking (em)
    ("WORDMARK", "Coda", "ArchivoBlack-Regular.ttf", 50, -0.04),
    ("TAGLINE", "music, offline", "Inconsolata.ttf", 12, 0.0),
)


def bake(name, text, font, px, track):
    f = ImageFont.truetype(str(FONTS / font), px * SS)
    asc, desc = f.getmetrics()
    w = int(sum(f.getlength(c) for c in text) + 40 * SS)
    img = Image.new("L", (w, asc + desc + 8 * SS), 0)
    d = ImageDraw.Draw(img)
    x = 4 * SS
    for c in text:
        d.text((x, 4 * SS), c, font=f, fill=255)
        x += f.getlength(c) + track * px * SS
    a = np.asarray(img, dtype=np.float32)
    h4, w4 = a.shape[0] // SS * SS, a.shape[1] // SS * SS
    a = a[:h4, :w4].reshape(h4 // SS, SS, w4 // SS, SS).mean(axis=(1, 3))
    ys, xs = np.nonzero(a > 2)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    a = np.clip(a[y0:y1, x0:x1] + 0.5, 0, 255).astype(np.uint8)
    baseline = (4 * SS + asc) // SS - y0                     # rows from the top to the baseline
    rows = [", ".join(str(v) for v in r) for r in a]
    low = name.lower()
    return (f"/* \"{text}\", {font[:-4]}, {px}px */\n"
            f"#define {name}_W {a.shape[1]}\n#define {name}_H {a.shape[0]}\n"
            f"#define {name}_BASELINE {baseline}\n"
            f"static const uint8_t {low}_a8[{name}_W * {name}_H] = {{\n"
            + ",\n".join("    " + r for r in rows) + "\n};\n"), a.shape


def main():
    body = []
    for p in PARTS:
        src, shape = bake(*p)
        body.append(src)
        print(f"{p[0]}: {shape[1]}x{shape[0]}")
    OUT.write_text(
        "/* generated by firmware/tools/gen_wordmark.py -- 8-bit alpha, baked into the firmware */\n"
        "#ifndef CODA_WORDMARK_H\n#define CODA_WORDMARK_H\n#include <stdint.h>\n"
        + "".join(body) + "#endif\n", newline="\n")


if __name__ == "__main__":
    main()
