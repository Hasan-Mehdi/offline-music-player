r"""Expected outputs of CPython's random module for firmware/host/test_pyrand.c.
  .venv\Scripts\python firmware\tools\gen_pyrand_golden.py   (writes host/pyrand_golden.h)"""
import hashlib
import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "host" / "pyrand_golden.h"


def arr(name, vals, fmt):
    return f"static const {name}[] = {{ " + ", ".join(fmt % v for v in vals) + " };\n"


def main():
    s = []
    s.append("/* generated by firmware/tools/gen_pyrand_golden.py from CPython's random */\n")
    s.append('static const char SHA_MSG[] = "dQw4w9WgXcQ";\n')
    s.append(f'static const char SHA_HEX[] = "{hashlib.sha512(b"dQw4w9WgXcQ").hexdigest()}";\n')
    r = random.Random("dQw4w9WgXcQ")
    s.append(arr("double STR_RANDOM", [r.random() for _ in range(5)], "%.17g"))
    s.append(arr("unsigned GETBITS7", [r.getrandbits(7) for _ in range(8)], "%du"))
    r = random.Random(12345)
    s.append(arr("double INT_RANDOM", [r.random() for _ in range(3)], "%.17g"))
    r = random.Random("~AbCdEfGhI")
    s.append(arr("unsigned SAMPLE_POOL", r.sample(list(range(60)), 10), "%du"))
    s.append(arr("unsigned SAMPLE_SET", r.sample(list(range(1000)), 10), "%du"))
    s.append(arr("unsigned BELOW", [r._randbelow(n) for n in (1, 2, 3, 100, 1000, 65537)], "%du"))
    r = random.Random(7)
    s.append(arr("double BETA", [r.betavariate(a, b) for a, b in
                                 ((3.5, 7.2), (1.0, 1.0), (0.4, 2.0), (12.0, 3.0), (2.0, 0.6))],
                 "%.17g"))
    s.append(arr("double GAMMA", [r.gammavariate(a, 1.0) for a in (0.3, 1.0, 5.5)], "%.17g"))
    OUT.write_text("".join(s), newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
