#!/usr/bin/env python3
"""Coda OS strip build: the plugin API table with only what Coda calls.

Rockbox's apps/plugin.c fills a struct plugin_api with ~800 core functions -- the whole UI
(lists, skins, WPS, menus, keyboard, file browser...). Every one of them is a reference that
keeps that code linked into the firmware. Coda reaches the core only through rb->, so this
writes the same initializer with every entry Coda doesn't use replaced by 0; the linker's
--gc-sections then drops the UI that nothing references any more.

  gen_api_table.py <plugin.i (preprocessed apps/plugin.c)> <out.h> <coda sources...>

The struct layout is untouched (Coda is compiled against the real plugin.h); only the
values change.
"""
import re
import sys
from pathlib import Path


def body_after(text, start_pat):
    m = re.search(start_pat, text)
    if not m:
        raise SystemExit(f"not found: {start_pat}")
    i = m.end()
    depth, j = 1, i
    while depth:
        c = text[j]
        depth += c == "{"
        depth -= c == "}"
        j += 1
    return text[i:j - 1]


def split_top(s, sep):
    out, depth, cur = [], 0, []
    for c in s:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == sep and depth == 0:
            out.append("".join(cur))
            cur = []
        else:
            cur.append(c)
    if "".join(cur).strip():
        out.append("".join(cur))
    return out


def member_name(decl):
    decl = " ".join(decl.split())
    m = re.search(r"\(\s*\*\s*(\w+)\s*\)\s*\(", decl)        # function pointer
    if m:
        return m.group(1)
    m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", decl)          # data pointer / array
    return m.group(1)


def main():
    pp, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = pp.read_text(errors="replace")
    text = re.sub(r"^#.*$", "", text, flags=re.M)               # line markers
    text = re.sub(r"__attribute__\s*\(\(.*?\)\)", "", text)
    fields = [member_name(d) for d in split_top(body_after(text, r"struct\s+plugin_api\s*\{"), ";")
              if d.strip()]
    init = [e.strip() for e in split_top(body_after(text, r"rockbox_api\s*=\s*\{"), ",")]
    if init and not init[-1]:
        init.pop()
    if len(fields) != len(init):
        raise SystemExit(f"field/initializer count mismatch: {len(fields)} vs {len(init)}")
    used = set()
    for src in sys.argv[3:]:
        used |= set(re.findall(r"rb->(\w+)", Path(src).read_text(errors="replace")))
    aliases = {"splash": "splashf"}                  # plugin.h: #define splash(t, s) splashf(t, s)
    used = {aliases.get(u, u) for u in used}
    missing = used - set(fields)
    if missing:
        raise SystemExit(f"Coda uses rb-> names the API doesn't have: {sorted(missing)}")
    lines = [f"    {e if f in used else '0'}, /* {f} */" for f, e in zip(fields, init)]
    out.write_text("/* generated by gen_api_table.py: rockbox_api with only Coda's entries */\n"
                   + "\n".join(lines) + "\n")
    print(f"api table: {len(used)} of {len(fields)} entries kept -> {out}")


if __name__ == "__main__":
    main()
