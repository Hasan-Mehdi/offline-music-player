#!/usr/bin/env python3
r"""ListenBrainz as a discovery source — the one signal the local engine lacks:
cross-user collaborative filtering. Two jobs in one resumable script:

1. SUBMIT: backfill your listening history (Takeout watch-history.json files +
   the player's `plays` table 'complete' events) as ListenBrainz listens, so
   their CF batch jobs can build a taste profile for you.
2. RECS: pull back the generated recommendations (Weekly Exploration playlist +
   raw CF recording recs), drop everything you already own or queued, resolve
   the rest to YouTube video ids via ytmusicapi, and write
   data/listenbrainz_candidates.csv in the download-queue column format
   (download.ps1 -InputCsv data\listenbrainz_candidates.csv).

Setup (one time): create an account at https://listenbrainz.org, copy the user
token from Settings, then either set LISTENBRAINZ_TOKEN or write it to
data/listenbrainz.json as {"token": "..."}.

Notes: recommendations are generated by ListenBrainz in periodic batch runs —
right after your FIRST import expect them to be empty; re-run in a few days.
State (what's been submitted, ytmusic resolution cache) lives in
data/listenbrainz_state.json; re-running never double-submits (and ListenBrainz
dedupes identical listens server-side anyway).

Usage:
  .venv\Scripts\python scripts\harvest_listenbrainz.py --dry-run
  .venv\Scripts\python scripts\harvest_listenbrainz.py            # submit + recs
  .venv\Scripts\python scripts\harvest_listenbrainz.py --no-submit --max-recs 300
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sqlite3
import sys
import time
import unicodedata
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).parent))
import parse_takeout_history as takeout  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
API = "https://api.listenbrainz.org"
BATCH = 500                 # listens per submit request (server max is 1000)
CLIENT = "offline-music-player/1.0"


# --------------------------------------------------------------------- helpers

def norm(s: str) -> str:
    """Aggressive title/artist normalizer for own-it-already matching: if we own
    ANY version of a rec, the rec is redundant (mirrors curate.py philosophy)."""
    s = unicodedata.normalize("NFKD", s or "").casefold()
    s = "".join(c for c in s if not unicodedata.combining(c))
    for cut in (" feat.", " feat ", " ft.", " ft ", " featuring "):
        i = s.find(cut)
        if i > 0:
            s = s[:i]
    out, depth = [], 0
    for c in s:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth = max(0, depth - 1)
        elif depth == 0:
            out.append(c if c.isalnum() else " ")
    return " ".join("".join(out).split())


def nkey(artist: str, title: str) -> str:
    return norm(artist) + "||" + norm(title)


def load_state(path: Path) -> dict:
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"submitted_max_ts": 0.0, "total_submitted": 0, "resolve_cache": {}}


def save_state(path: Path, state: dict) -> None:
    path.write_text(json.dumps(state), encoding="utf-8")


# --------------------------------------------------------------------- listens

def takeout_paths(extra: list[Path]) -> list[Path]:
    cands = [ROOT / "data" / "takeout" / "YouTube and YouTube Music" / "history" / "watch-history.json"]
    downloads = Path.home() / "Downloads"
    if downloads.exists():
        cands += sorted(downloads.glob("takeout-*/Takeout/YouTube and YouTube Music/history/watch-history.json"))
    cands += extra
    seen, out = set(), []
    for p in cands:
        if p.exists() and p.resolve() not in seen:
            seen.add(p.resolve())
            out.append(p)
    return out


def listens_from_takeout(path: Path) -> list[dict]:
    entries = json.loads(path.read_text(encoding="utf-8"))
    out = []
    for e in entries:
        if e.get("details") and any(d.get("name") == "From Google Ads" for d in e["details"]):
            continue
        if not takeout.is_music_entry(e):
            continue
        artist, title = takeout.clean_artist(e), takeout.clean_title(e)
        t = takeout.parse_time(e.get("time", ""))
        vid = takeout.video_id_from_url(e.get("titleUrl", ""))
        if not artist or not title or t is None:
            continue
        out.append({
            "ts": int(t.timestamp()), "artist": artist, "title": title,
            "album": "", "duration": None, "vid": vid or "",
            "service": "music.youtube.com",
        })
    return out


def listens_from_plays(db_path: Path) -> list[dict]:
    if not db_path.exists():
        return []
    con = sqlite3.connect(f"file:{db_path.as_posix()}?mode=ro", uri=True, timeout=15)
    con.execute("PRAGMA busy_timeout=10000")
    rows = con.execute(
        "SELECT p.ts, p.video_id, t.artist, t.title, t.album, t.duration "
        "FROM plays p JOIN tracks t ON t.video_id = p.video_id "
        "WHERE p.event = 'complete' AND p.ts IS NOT NULL").fetchall()
    con.close()
    return [{"ts": int(ts), "artist": a or "", "title": ti or "", "album": al or "",
             "duration": d, "vid": v, "service": "local"}
            for ts, v, a, ti, al, d in rows if a and ti]


def to_payload(ls: dict) -> dict:
    info = {"submission_client": CLIENT}
    if ls["duration"]:
        info["duration_ms"] = int(ls["duration"] * 1000)
    if ls["vid"]:
        info["origin_url"] = f"https://music.youtube.com/watch?v={ls['vid']}"
    if ls["service"] == "music.youtube.com":
        info["music_service"] = "music.youtube.com"
    else:
        info["media_player"] = "offline-music-player"
    tm = {"artist_name": ls["artist"], "track_name": ls["title"], "additional_info": info}
    if ls["album"]:
        tm["release_name"] = ls["album"]
    return {"listened_at": ls["ts"], "track_metadata": tm}


# ------------------------------------------------------------------------- api

def api_call(sess: requests.Session, method: str, path: str, **kw):
    for _ in range(4):
        r = sess.request(method, API + path, timeout=30, **kw)
        if r.status_code == 429:
            wait = float(r.headers.get("X-RateLimit-Reset-In", 5)) + 0.5
            print(f"  rate limited, sleeping {wait:.0f}s")
            time.sleep(wait)
            continue
        return r
    return r


def submit_listens(sess: requests.Session, listens: list[dict]) -> int:
    sent = 0
    for i in range(0, len(listens), BATCH):
        chunk = listens[i:i + BATCH]
        r = api_call(sess, "POST", "/1/submit-listens",
                     json={"listen_type": "import", "payload": [to_payload(x) for x in chunk]})
        if r.status_code != 200:
            print(f"  submit failed at batch {i // BATCH}: HTTP {r.status_code} {r.text[:200]}")
            break
        sent += len(chunk)
        print(f"  submitted {sent}/{len(listens)}", end="\r", flush=True)
        time.sleep(0.4)
    print()
    return sent


def fetch_recs(sess: requests.Session, user: str, max_recs: int, include_jams: bool) -> list[dict]:
    recs = []
    r = api_call(sess, "GET", f"/1/user/{user}/playlists/createdfor")
    if r.status_code == 200:
        for entry in r.json().get("playlists", []):
            pl = entry.get("playlist", {})
            title = pl.get("title", "")
            want = "Exploration" in title or (include_jams and "Jams" in title)
            if not want:
                continue
            mbid = pl.get("identifier", "").rstrip("/").rsplit("/", 1)[-1]
            pr = api_call(sess, "GET", f"/1/playlist/{mbid}")
            if pr.status_code != 200:
                continue
            for tr in pr.json().get("playlist", {}).get("track", []):
                if tr.get("creator") and tr.get("title"):
                    recs.append({"artist": tr["creator"], "title": tr["title"],
                                 "source": title, "score": ""})
            print(f"  playlist '{title}': {len(recs)} tracks so far")
    else:
        print(f"  createdfor playlists: HTTP {r.status_code} (none generated yet?)")

    r = api_call(sess, "GET", f"/1/cf/recommendation/user/{user}/recording",
                 params={"count": max_recs})
    if r.status_code == 200:
        mbids = [(m.get("recording_mbid"), m.get("score"))
                 for m in r.json().get("payload", {}).get("mbids", [])]
        for i in range(0, len(mbids), 50):
            chunk = mbids[i:i + 50]
            mr = api_call(sess, "GET", "/1/metadata/recording/",
                          params={"recording_mbids": ",".join(m for m, _ in chunk), "inc": "artist"})
            if mr.status_code != 200:
                break
            meta = mr.json()
            for mbid, score in chunk:
                m = meta.get(mbid) or {}
                name = (m.get("recording") or {}).get("name")
                artist = (m.get("artist") or {}).get("name")
                if name and artist:
                    recs.append({"artist": artist, "title": name,
                                 "source": "cf-recording", "score": score})
        print(f"  cf recommendations: {len(mbids)} mbids")
    else:
        print(f"  cf recommendations: HTTP {r.status_code} (batch not run yet for this account?)")
    return recs


# ------------------------------------------------------------------- filtering

def owned_keys(db_path: Path) -> tuple[set, set]:
    keys, vids = set(), set()
    if db_path.exists():
        con = sqlite3.connect(f"file:{db_path.as_posix()}?mode=ro", uri=True, timeout=15)
        con.execute("PRAGMA busy_timeout=10000")
        for a, t, v in con.execute("SELECT artist, title, video_id FROM tracks"):
            keys.add(nkey(a or "", t or ""))
            vids.add(v)
        con.close()
    arch = ROOT / "data" / "downloaded.txt"
    if arch.exists():
        for line in arch.read_text(encoding="utf-8", errors="replace").splitlines():
            parts = line.split()
            if len(parts) == 2:
                vids.add(parts[1])
    queue = ROOT / "data" / "download_queue.csv"
    if queue.exists():
        with queue.open(encoding="utf-8", newline="") as fh:
            for row in csv.DictReader(fh):
                if row.get("video_id"):
                    vids.add(row["video_id"])
                keys.add(nkey(row.get("artist", ""), row.get("title", "")))
    return keys, vids


def resolve_ytmusic(cands: list[dict], cache: dict) -> list[dict]:
    from ytmusicapi import YTMusic
    yt = YTMusic()
    out = []
    for c in cands:
        key = nkey(c["artist"], c["title"])
        if key in cache:
            hit = cache[key]
        else:
            hit = None
            try:
                results = yt.search(f"{c['artist']} {c['title']}", filter="songs", limit=5)
            except Exception as e:
                print(f"  ytmusic search failed for {c['artist']} - {c['title']}: {e}")
                results = []
            na = norm(c["artist"])
            best = None
            for res in results or []:
                if not res.get("videoId"):
                    continue
                ra = norm(" ".join(a.get("name", "") for a in res.get("artists", [])))
                exact = na and (na in ra or ra in na)
                if best is None or (exact and not best[1]):
                    dur = res.get("duration_seconds") or 0
                    best = (res, exact, dur)
                if exact:
                    break
            if best and (best[2] == 0 or best[2] >= 30):
                res, exact, dur = best
                hit = {"video_id": res["videoId"],
                       "album": (res.get("album") or {}).get("name", "") if isinstance(res.get("album"), dict) else "",
                       "duration": dur, "match": "artist" if exact else "loose"}
            cache[key] = hit
            time.sleep(0.35)
        if hit:
            out.append({**c, **hit})
    return out


# ------------------------------------------------------------------------ main

def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", type=Path, default=ROOT / "data" / "library.db")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "listenbrainz_candidates.csv")
    ap.add_argument("--takeout", type=Path, nargs="*", default=[],
                    help="extra watch-history.json paths (known locations auto-discovered)")
    ap.add_argument("--max-recs", type=int, default=200)
    ap.add_argument("--include-jams", action="store_true",
                    help="also mine Weekly Jams (tracks you already know; off by default)")
    ap.add_argument("--no-submit", action="store_true")
    ap.add_argument("--no-recs", action="store_true")
    ap.add_argument("--resubmit-all", action="store_true",
                    help="ignore local state and resend everything (server dedupes)")
    ap.add_argument("--dry-run", action="store_true", help="parse and report only, no network")
    args = ap.parse_args(argv)

    state_path = ROOT / "data" / "listenbrainz_state.json"
    state = load_state(state_path)

    # ---- gather listens
    listens, by_key = [], set()
    for p in takeout_paths(list(args.takeout)):
        got = listens_from_takeout(p)
        fresh = 0
        for ls in got:
            k = (ls["ts"], ls["vid"] or nkey(ls["artist"], ls["title"]))
            if k not in by_key:
                by_key.add(k)
                listens.append(ls)
                fresh += 1
        print(f"takeout {p}: {len(got)} music listens ({fresh} new vs other files)")
    plays = listens_from_plays(args.db)
    for ls in plays:
        k = (ls["ts"], ls["vid"])
        if k not in by_key:
            by_key.add(k)
            listens.append(ls)
    print(f"player plays table: {len(plays)} completed listens")
    listens.sort(key=lambda x: x["ts"])
    cutoff = 0.0 if args.resubmit_all else state["submitted_max_ts"]
    new = [x for x in listens if x["ts"] > cutoff]
    print(f"total {len(listens)} listens, {len(new)} not yet submitted")

    if args.dry_run:
        print("dry run — stopping before network calls")
        return 0

    token = os.environ.get("LISTENBRAINZ_TOKEN", "")
    cfg = ROOT / "data" / "listenbrainz.json"
    if not token and cfg.exists():
        token = json.loads(cfg.read_text(encoding="utf-8")).get("token", "")
    if not token:
        print("\nNo token. Create an account at https://listenbrainz.org, copy the user")
        print("token from Settings, then set LISTENBRAINZ_TOKEN or write data/listenbrainz.json")
        print('as {"token": "YOUR-TOKEN"} and re-run.')
        return 1

    sess = requests.Session()
    sess.headers.update({"Authorization": f"Token {token}", "User-Agent": CLIENT})
    r = api_call(sess, "GET", "/1/validate-token")
    if r.status_code != 200 or not r.json().get("valid"):
        print(f"token rejected: HTTP {r.status_code} {r.text[:200]}")
        return 1
    user = r.json().get("user_name", "")
    print(f"authenticated as ListenBrainz user '{user}'")

    if not args.no_submit and new:
        sent = submit_listens(sess, new)
        if sent:
            state["submitted_max_ts"] = max(x["ts"] for x in new[:sent])
            state["total_submitted"] += sent
            save_state(state_path, state)
        print(f"submitted {sent} listens (lifetime {state['total_submitted']})")

    if args.no_recs:
        return 0

    print("fetching recommendations...")
    recs = fetch_recs(sess, user, args.max_recs, args.include_jams)
    if not recs:
        print("no recommendations yet — ListenBrainz generates them in periodic batch")
        print("runs after your first import; re-run this script in a few days.")
        return 0

    keys, vids = owned_keys(args.db)
    seen, fresh_recs = set(), []
    for c in recs:
        k = nkey(c["artist"], c["title"])
        if k in keys or k in seen:
            continue
        seen.add(k)
        fresh_recs.append(c)
    print(f"{len(recs)} recs -> {len(fresh_recs)} not owned/queued; resolving on YT Music...")

    resolved = resolve_ytmusic(fresh_recs, state["resolve_cache"])
    save_state(state_path, state)
    rows = [c for c in resolved if c["video_id"] not in vids]

    with args.out.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["video_id", "title", "artist", "album",
                                           "curated_freq", "playlist_freq", "url",
                                           "lb_source", "lb_score", "match"])
        w.writeheader()
        done = set()
        for c in rows:
            if c["video_id"] in done:
                continue
            done.add(c["video_id"])
            w.writerow({"video_id": c["video_id"], "title": c["title"], "artist": c["artist"],
                        "album": c.get("album", ""), "curated_freq": 3, "playlist_freq": 0,
                        "url": f"https://music.youtube.com/watch?v={c['video_id']}",
                        "lb_source": c["source"], "lb_score": c["score"], "match": c["match"]})
    print(f"wrote {len(done)} candidates to {args.out}")
    print(f"download with:  scripts\\download.ps1 -InputCsv {args.out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
